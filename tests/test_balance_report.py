import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPORT = ROOT / "docs" / "balance" / "report.md"
TOLERANCES = ROOT / "docs" / "balance" / "tolerances.md"
ROW = re.compile(r"^\| (Z\d+) \|.*\| (OUT|in target) \|$")
RANGE_ROW = re.compile(r"^\| (Z\d+) \| [^|]* \| [^|]* \| (-?\d+(?:\.\d+)?) to (-?\d+(?:\.\d+)?) \| [^|]* \|$")
MEDIAN = re.compile(r"median (-?\d+(?:\.\d+)?)")
PERCENT = re.compile(r"^(-?\d+(?:\.\d+)?) %$")


def report_text():
    return REPORT.read_text(encoding="utf-8")


def tolerance_text():
    return TOLERANCES.read_text(encoding="utf-8")


def rows():
    return {m.group(1): m.group(2) for m in map(ROW.match, report_text().splitlines()) if m}


def measured(report):
    """The Measured cell of every Z row of the report."""
    cells = {}
    for line in report.splitlines():
        if line.startswith("| Z"):
            parts = [part.strip() for part in line.strip("|").split("|")]
            cells[parts[0]] = parts[3]
    return cells


def figures(cell):
    """The median of each figure in a Measured cell; Z8 has a single percentage instead."""
    found = MEDIAN.findall(cell)
    percent = PERCENT.match(cell)
    if not found and percent:
        found = [percent.group(1)]
    return [float(value) for value in found]


def ranges(tolerance):
    """Per Z row: the (low, high) range of each figure, in table order."""
    result = {}
    for line in tolerance.splitlines():
        m = RANGE_ROW.match(line)
        if m:
            result.setdefault(m.group(1), []).append((float(m.group(2)), float(m.group(3))))
    return result


def outside(report, tolerance):
    """Problems: a median outside its range, or a figure count that does not match the table."""
    cells = measured(report)
    problems = []
    for row, bounds in ranges(tolerance).items():
        values = figures(cells.get(row, ""))
        if len(values) != len(bounds):
            problems.append(f"{row}: {len(values)} measured figures for {len(bounds)} ranges")
            continue
        for value, (low, high) in zip(values, bounds):
            if not low <= value <= high:
                problems.append(f"{row}: {value:g} outside {low:g} to {high:g}")
    return problems


def test_report_has_all_eleven_targets():
    assert sorted(rows(), key=lambda z: int(z[1:])) == [f"Z{i}" for i in range(1, 12)]


def test_out_of_target_count_matches_rows():
    out = sum(1 for status in rows().values() if status == "OUT")
    assert f"Out of target: {out} of 11 rows" in report_text()


def test_report_is_marked_as_generated():
    assert "Generated by `lune run scripts/balance`" in report_text()


def test_measured_values_inside_tolerances():
    assert sorted(ranges(tolerance_text()), key=lambda z: int(z[1:])) == [f"Z{i}" for i in range(1, 11)]
    assert outside(report_text(), tolerance_text()) == []


def test_value_moved_outside_tolerance_fails():
    moved = report_text().replace("median 19.1 min", "median 30.0 min", 1)
    assert outside(moved, tolerance_text()) == ["Z1: 30 outside 15 to 22"]
